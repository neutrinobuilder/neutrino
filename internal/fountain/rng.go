package fountain

// splitmix64 — minimal deterministic PRNG, a well-documented public
// algorithm (Vigna, 2015). math/rand is not used: its output for a given
// seed is not guaranteed stable across Go toolchain versions, while here
// the exact correspondence between the sequence generated by the encoder
// and the one regenerated by the decoder — potentially on a binary built
// with a different Go version — is the only thing that makes a symbol
// reconstructible from its SymbolID alone. A self-contained
// implementation removes any risk of an external library changing it
// unexpectedly.
type splitmix64 struct{ state uint64 }

func newSplitmix64(seed uint32) *splitmix64 {
	return &splitmix64{state: uint64(seed) ^ 0x9E3779B97F4A7C15}
}

func (s *splitmix64) next() uint64 {
	s.state += 0x9E3779B97F4A7C15
	z := s.state
	z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9
	z = (z ^ (z >> 27)) * 0x94D049BB133111EB
	z = z ^ (z >> 31)
	return z
}

// float64 returns a value in [0,1) with 53 bits of mantissa, the same
// scheme as the standard library's rand.Float64().
func (s *splitmix64) float64() float64 {
	return float64(s.next()>>11) / float64(uint64(1)<<53)
}

// intn returns an integer in [0,n) — negligible bias for the n values
// (number of blocks per transfer) relevant here, avoiding the complexity
// of exact uniform rejection for a non-cryptographic use case.
func (s *splitmix64) intn(n int) int {
	return int(s.next() % uint64(n))
}
