// pingMissThreshold, how many consecutive ping cycles with no pong to
// tolerate before declaring a connection dead (see the ping/pong goroutine
// further below, and the identical counter client-side in
// internal/client/tui/tui.go pingWatchdogTickMsg). A single missed pong
// isn't reliable over Tor.
const pingMissThreshold = 2

// ── outgoing server → client ──────────────────────────────────────────────────

type wsInitMsg struct {
	Type  string     `json:"type"`
	Users []userInfo `json:"users"`
}

// wsRawChatMsg wraps a broadcast message for fan-out.
// Text is json.RawMessage so the ciphertext bytes can be zeroed after delivery.
type wsRawChatMsg struct {
	Type string       `json:"type"`
	Data wsRawMsgData `json:"data"`
}

type wsRawMsgData struct {
	KeyID      string          `json:"kid"`  // opaque key identifier, receiver uses it to find the right ratchet
	Text       json.RawMessage `json:"text"` // raw JSON string token, zeroed after delivery
	Idx        uint64          `json:"idx"`  // ratchet message index
	MsgSeq     uint64          `json:"mseq"` // sender's own outgoing sequence, never resets on key rotation, distinct from Idx (see Client.outMsgSeq)
	GSeq       uint64          `json:"gseq"` // ROOM-wide global sequence number, assigned by the server on arrival (roomDelivery), independent of MsgSeq (per-sender) and Idx (per-ratchet); basis for the explicit reply reference client-side (sealedMsg.RT, /msg N command)
	Timestamp  time.Time       `json:"timestamp"`
	Sig        string          `json:"sig,omitempty"`
	SigTS      string          `json:"sig_ts,omitempty"`
	FromUserID string          `json:"from_user_id"`     // ephemeral session UUID, needed to route ACKs back; not linked to identity
	MsgID      string          `json:"msg_id,omitempty"` // random ID generated by sender, correlates ACKs; string (decimal), not JSON number, see wsIncoming.MsgID
	// ContentSigs/ContentSigTS, multiple ContentKey-per-relationship
	// signature (see shared.ContentSigEntry), one entry per other room
	// member with whom the sender has an established relationship. Relayed
	// intact, never inspected here: the server has no (and shouldn't have
	// any) access to any ContentKey to verify them.
	ContentSigs  []shared.ContentSigEntry `json:"content_sigs,omitempty"`
	ContentSigTS string                   `json:"content_sig_ts,omitempty"`
	// DeviceSig/DeviceTS, device-level Ed25519 signature, verified by the receiver against DP inside the
	// just-decrypted ciphertext. PqcSig/PqcTS, optional per-room ML-DSA-65
	// signature (hybrid PQC network identity, /sec-pqc-sign), verified
	// against Contact.MLDSAPub. Both relayed intact, never inspected here,
	// the server verifies neither this nor any content signature.
	DeviceSig string `json:"device_sig,omitempty"`
	DeviceTS  string `json:"device_ts,omitempty"`
	PqcSig    string `json:"pqc_sig,omitempty"`
	PqcTS     string `json:"pqc_ts,omitempty"`
}

type wsUserLeft struct {
	Type   string `json:"type"`
	UserID string `json:"user_id"`
	Reason string `json:"reason"` // "left" = clean /grp-exit | "lost" = crash/timeout | "banned" = /grp-ban | "overloaded" = kick for a saturated delivery queue (roomDelivery), not a ban
}

type wsUserJoined struct {
	Type        string `json:"type"`
	UserID      string `json:"user_id"`
	Username    string `json:"username"`
	SessionPub  string `json:"session_pub,omitempty"`
	MLKEMPub    []byte `json:"mlkem_pub,omitempty"`    // see HandshakeResult.PeerMLKEMPub
	IdentityPub []byte `json:"identity_pub,omitempty"` // see userInfo.IdentityPub
}

type wsServerShutdown struct {
	Type string `json:"type"`
}

// wsSenderKeyFwd routes an ECIES-encrypted sender key to a specific peer.
// Payload is json.RawMessage so it can be zeroed after routing.
type wsSenderKeyFwd struct {
	Type       string          `json:"type"`
	FromUserID string          `json:"from_user_id"`
	Payload    json.RawMessage `json:"payload"`
	MsgID      string          `json:"msg_id,omitempty"` // reliable delivery: ack correlation (see Client.sendSenderKeyTo)
}

// wsRelBootstrapFwd routes an encrypted shared.RelBootstrapPayload (see
// shared.EncryptRelBootstrap) to a specific peer, same scheme as
// wsSenderKeyFwd, for the ephemeral relationship-key exchange between
// "introduced" members.
type wsRelBootstrapFwd struct {
	Type       string          `json:"type"`
	FromUserID string          `json:"from_user_id"`
	Payload    json.RawMessage `json:"payload"`
}

// wsRelBootstrapAckFwd routes the confirmation that a rel_bootstrap was
// received AND applied back to its original sender, same minimal scheme
// as wsMsgAckFwd (no encrypted payload: an ack carries no key material, see
// Client.SendRelBootstrapAck).
type wsRelBootstrapAckFwd struct {
	Type       string `json:"type"`
	FromUserID string `json:"from_user_id"`
}

// wsRelPromoteFwd routes an encrypted shared.RelPromotePayload (see
// shared.EncryptRelPromote) to a specific peer, same scheme as
// wsSenderKeyFwd, sent only when two members explicitly decide to become
// real contacts.
type wsRelPromoteFwd struct {
	Type       string          `json:"type"`
	FromUserID string          `json:"from_user_id"`
	Payload    json.RawMessage `json:"payload"`
}

// wsRelPromoteAckFwd, see wsRelBootstrapAckFwd above, same scheme for
// rel_promote (Client.SendRelPromoteAck).
type wsRelPromoteAckFwd struct {
	Type       string `json:"type"`
	FromUserID string `json:"from_user_id"`
}

// wsPingProbeMsg routes a latency probe to a specific peer.
type wsPingProbeMsg struct {
	Type       string `json:"type"`
	FromUserID string `json:"from_user_id"`
	Seq        uint64 `json:"seq"`
	SentAt     int64  `json:"sent_at"` // Unix nanoseconds (sender clock)
}

// wsPongProbeMsg routes the probe reply back to the original sender.
type wsPongProbeMsg struct {
	Type       string `json:"type"`
	FromUserID string `json:"from_user_id"`
	Seq        uint64 `json:"seq"`
	SentAt     int64  `json:"sent_at"` // echoed verbatim from ping
}

// wsMsgAckFwd routes a delivery ACK to the original message sender.
type wsMsgAckFwd struct {
	Type       string `json:"type"`
	FromUserID string `json:"from_user_id"` // session UUID of the peer who ACKed
	MsgID      string `json:"msg_id"`
}

// wsFileAnnounceFwd routes a file-transfer ANNOUNCE to ONE recipient, a
// single Send, same scheme as wsFileOfferFwd below. The cryptographic
// verification phase precedes any actual data, Hash is the shared
// ciphertext's hash (common to all recipients), Sig/SigMLDSA is THIS
// recipient's signature over that hash (shared.FileAnnounceEnvelope). No
// file name, no size, no file key, those arrive only inside the real
// file_offer, after the recipient has already confirmed the signature.
type wsFileAnnounceFwd struct {
	Type       string `json:"type"`
	FromUserID string `json:"from_user_id"`
	TransferID string `json:"transfer_id"`
	Hash       []byte `json:"hash"`
	Sig        []byte `json:"sig"`
	SigMLDSA   []byte `json:"sig_mldsa,omitempty"`
	SigTS      string `json:"sig_ts"`
}

// wsFileAnnounceAckFwd routes the recipient's confirmation that the
// announce signature verified (right away, or after a self-heal) back to
// the original sender only, same scheme as wsFileAcceptFwd. Only after
// this ack does the sender send the real file_offer to that recipient.
type wsFileAnnounceAckFwd struct {
	Type       string `json:"type"`
	FromUserID string `json:"from_user_id"`
	TransferID string `json:"transfer_id"`
}

// wsFileOfferFwd routes a file-transfer offer to ONE recipient, a single
// Send, not a Multicast (unlike file_chunk, which shares the same
// ciphertext for everyone). Carries no signature: whoever receives it has
// already verified the sender's authenticity during the announce phase,
// this frame carries only the meta_blob encrypted specifically for them
// (shared.FileOfferEnvelope), never a value shared across recipients.
// FileName/FileSize don't travel in plaintext: they're inside MetaBlob,
// the server never uses them for any logic (the size limit is enforced
// sender-side only), so it has no reason to see them in plaintext.
type wsFileOfferFwd struct {
	Type       string `json:"type"`
	FromUserID string `json:"from_user_id"`
	TransferID string `json:"transfer_id"`
	MetaBlob   string `json:"meta_blob"` // shared.EncryptForPeer toward THIS recipient's ContentKey: {file_name, file_size, file_key}
}

// wsFileAcceptFwd / wsFileRejectFwd route the recipient's decision on a
// file_offer back to the original sender only.
type wsFileAcceptFwd struct {
	Type       string `json:"type"`
	FromUserID string `json:"from_user_id"`
	TransferID string `json:"transfer_id"`
}

type wsFileRejectFwd struct {
	Type       string `json:"type"`
	FromUserID string `json:"from_user_id"`
	TransferID string `json:"transfer_id"`
}

// wsFileChunkFwd routes one ciphertext chunk to the recipients who accepted
// (multicast). Payload is a byte-range slice of the ciphertext already
// encrypted once for all recipients, no per-chunk crypto cost.
type wsFileChunkFwd struct {
	Type       string          `json:"type"`
	FromUserID string          `json:"from_user_id"`
	TransferID string          `json:"transfer_id"`
	Seq        uint64          `json:"seq"`
	Payload    json.RawMessage `json:"payload"`
}

// wsFileChunkAckFwd routes a per-chunk ACK back to the sender only, driving
// the sliding-window pipeline (FileWarpMaxInFlightChunks / FileSlowMaxInFlightChunks).
type wsFileChunkAckFwd struct {
	Type       string `json:"type"`
	FromUserID string `json:"from_user_id"`
	TransferID string `json:"transfer_id"`
	Seq        uint64 `json:"seq"`
}

// wsFileVerifyResultFwd routes the RECIPIENT's final verify/decrypt outcome
// back to the original sender only, see the comment on wsIncoming.VerifyOK
// for why this exists (file_chunk_ack alone only proves transport delivery).
type wsFileVerifyResultFwd struct {
	Type       string `json:"type"`
	FromUserID string `json:"from_user_id"`
	TransferID string `json:"transfer_id"`
	OK         bool   `json:"ok"`
}

// wsFileResumeFwd routes a resume announcement back to the original sender
// only: the recipient (own reconnect, or the sender's) reports how many bytes
// it already has for this transfer, so the sender can re-admit it into the
// sliding window from the right offset instead of restarting from scratch.
type wsFileResumeFwd struct {
	Type       string `json:"type"`
	FromUserID string `json:"from_user_id"`
	TransferID string `json:"transfer_id"`
	FromByte   int64  `json:"from_byte"`
}

type userInfo struct {
	UserID     string `json:"user_id"`
	Username   string `json:"username"`
	SessionPub string `json:"session_pub,omitempty"`
	MLKEMPub   []byte `json:"mlkem_pub,omitempty"` // see HandshakeResult.PeerMLKEMPub
	// IdentityPub is the member's root identity key (UserSession.RootIdentityPub):
	// what every client uses to tell members apart and to match one to a
	// contact. Username is only a display label.
	IdentityPub []byte `json:"identity_pub,omitempty"`
}

// ── incoming client → server ──────────────────────────────────────────────────

// wsIncoming is what the client sends over the WebSocket.
//
//	Type = ""                  → broadcast room message (Text, Idx, KeyID fields)
//	Type = "sender_key"        → ECIES-encrypted sender key for ToUserID (Payload field; msg_id optional, see Client.sendSenderKeyTo, reliable delivery via the generic msg_ack path, no dedicated ack type needed)
//	Type = "rel_bootstrap"     → ephemeral relation-key exchange for ToUserID (Payload field)
//	Type = "rel_bootstrap_ack" → confirms a rel_bootstrap was received AND applied, for ToUserID (no Payload)
//	Type = "rel_promote"       → "become a real contact" exchange for ToUserID (Payload field)
//	Type = "rel_promote_ack"   → confirms a rel_promote was received AND applied, for ToUserID (no Payload)
//
// Text and Payload are json.RawMessage ([]byte) so the ciphertext bytes can be
// explicitly zeroed after delivery instead of waiting for the GC.
type wsIncoming struct {
	Type  string          `json:"type,omitempty"`
	Text  json.RawMessage `json:"text,omitempty"` // broadcast: sealed AES-256-GCM payload
	Idx   uint64          `json:"idx,omitempty"`  // ratchet message index
	KeyID string          `json:"kid,omitempty"`  // opaque key identifier
	// MsgID is a decimal string, not a JSON number: the client's own ReadMsg decodes
	// generic frames into map[string]any, where encoding/json always turns JSON
	// numbers into float64, exact only up to 2^53, so a full-width random uint64
	// (as generated by Client.Send) gets silently corrupted on every round-trip
	// through that path. The server itself decodes into this typed struct either
	// way and wouldn't be affected, but the client is, so the wire format stays a
	// string end-to-end (like transfer_id) rather than relying on decoder-specific
	// handling.
	MsgID  string `json:"msg_id,omitempty"` // random ACK correlation ID
	MsgSeq uint64 `json:"mseq,omitempty"`   // broadcast: sender's own outgoing sequence, never resets on rotation (see Client.outMsgSeq), distinct from Seq below, which is used by other frame types
	Sig    string `json:"sig,omitempty"`
	SigTS  string `json:"sig_ts,omitempty"`
	// ContentSigs/ContentSigTS, see wsRawMsgData above.
	ContentSigs  []shared.ContentSigEntry `json:"content_sigs,omitempty"`
	ContentSigTS string                   `json:"content_sig_ts,omitempty"`
	// DeviceSig/DeviceTS/PqcSig/PqcTS, see wsRawMsgData above.
	DeviceSig string          `json:"device_sig,omitempty"`
	DeviceTS  string          `json:"device_ts,omitempty"`
	PqcSig    string          `json:"pqc_sig,omitempty"`
	PqcTS     string          `json:"pqc_ts,omitempty"`
	ToUserID  string          `json:"to_user_id,omitempty"`
	Payload   json.RawMessage `json:"payload,omitempty"` // ECIES payload for sender_key; ciphertext chunk for file_chunk
	Seq       uint64          `json:"seq,omitempty"`     // ping_probe / pong_probe sequence; file_chunk / file_chunk_ack sequence

	SentAt int64 `json:"sent_at,omitempty"` // ping_probe / pong_probe Unix nanoseconds

	// file_announce / file_offer / file_chunk (multicast) / file_accept /
	// file_reject / file_chunk_ack / file_resume.
	ToUserIDs  []string `json:"to_user_ids,omitempty"` // file_announce / file_offer / file_chunk: multicast recipients
	TransferID string   `json:"transfer_id,omitempty"` // all file_* frames
	// Hash/AnnounceEnvelopes, file_announce: the shared ciphertext's
	// common hash (not yet transferred) + a signature-only envelope per
	// recipient (key = to_user_id, shared.FileAnnounceEnvelope), see
	// wsFileAnnounceFwd above. SigTS (field above) is common to all
	// envelopes of this announcement.
	Hash              []byte                                 `json:"hash,omitempty"`
	AnnounceEnvelopes map[string]shared.FileAnnounceEnvelope `json:"announce_envelopes,omitempty"`
	// Envelopes, file_offer: one envelope per recipient (key =
	// to_user_id), see shared.FileOfferEnvelope and wsFileOfferFwd above,
	// just meta_blob, no signature (already verified during the announce
	// phase).
	Envelopes map[string]shared.FileOfferEnvelope `json:"envelopes,omitempty"`
	FromByte  int64                               `json:"from_byte,omitempty"` // file_resume: how many bytes the recipient already has
	// VerifyOK, file_verify_result: the recipient's signature/decryption
	// verification outcome, AFTER all chunks have already been confirmed
	// by file_chunk_ack, that ack alone only proves transport-level
	// delivery, never that the recipient actually verified/saved the file.
	// Fire-and-forget toward the original sender, same scheme as
	// file_chunk_ack/file_resume.
	VerifyOK bool `json:"verify_ok,omitempty"`
}

// ── handler ───────────────────────────────────────────────────────────────────

func (a *appCtx) handleWS(w http.ResponseWriter, r *http.Request) {
	if a.isSilenced() {
		http.NotFound(w, r)
		return
	}
	if !a.limiter.AllowRequest(r.RemoteAddr) {
		http.Error(w, "too many requests", http.StatusTooManyRequests)
		return
	}

	conn, err := websocket.Accept(w, r, &websocket.AcceptOptions{InsecureSkipVerify: true})
	if err != nil {
		return
	}
	defer conn.CloseNow()
	conn.SetReadLimit(shared.MaxFileChunkWireBytes(shared.DefaultFileWarpChunkSizeKiB * 1024))

	ctx, cancel := context.WithCancel(r.Context())
	defer cancel()

	// "One device per identity per room" must be enforced INSIDE the
	// handshake, BEFORE the server sends ServerHello: from the client's
	// point of view, DoClientHandshake returns successfully as soon as it
	// receives and verifies ServerHello, regardless of what the server does
	// AFTER DoServerHandshake returns, a rejection here in ws.go, further
	// downstream, would always arrive too late: the client would have
	// already considered the connection successful. userID generated
	// BEFORE the call (not after, like every other UserSession field)
	// because claimSlot needs it to register/replace the slot.
	userID := uuid.New().String()
	claimSlot := func(roomID string, identityPub, devicePub []byte) bool {
		room := a.registry.GetOrCreateRoom(roomID)
		evictUserID, ok := room.ClaimIdentitySlot(identityPub, devicePub, userID)
		if !ok {
			return false
		}
		if evictUserID != "" {
			room.hub.Kick(evictUserID)
		}
		return true
	}
	result, err := DoServerHandshake(ctx, conn, a.registry.LookupSecret, claimSlot)
	if err != nil {
		return
	}

	room := a.registry.GetOrCreateRoom(result.MatchedRoomID)

	username := result.PeerUsername
	if result.MatchedLabel != "" {
		username = result.MatchedLabel
	}

	sess := &UserSession{
		UserID:          userID,
		Username:        username,
		SessionKey:      result.SessionKey,
		CreatedAt:       time.Now().UTC(),
		LastSeen:        time.Now().UTC(),
		SessionPub:      result.PeerECIESPub,
		IdentityPub:     result.MatchedIdentityPub,
		RootIdentityPub: result.MatchedRootIdentityPub,
		MLKEMPub:        result.PeerMLKEMPub,
	}
	room.sessions.Add(sess)

	// Keepalive ping/pong goroutine. Tolerates pingMissThreshold consecutive
	// missed cycles before declaring the connection dead, a single
	// delayed pong (common on Tor under circuit stress, never a reliable
	// sign of a genuinely dead connection) must not be enough to throw out
	// a healthy member, a cascade that would then trigger both reconnection
	// bursts and other members' "wake" downstream. Any pong received resets
	// the counter.
	go func() {
		ticker := time.NewTicker(a.pingInterval)
		defer ticker.Stop()
		misses := 0
		for {
			select {
			case <-ctx.Done():
				return
			case <-ticker.C:
				pingCtx, pingCancel := context.WithTimeout(ctx, a.pingInterval/2)
				err := conn.Ping(pingCtx)
				pingCancel()
				if err != nil {
					misses++
					if misses >= pingMissThreshold {
						cancel()
						return
					}
					continue
				}
				misses = 0
			}
		}
	}()

	exitReason := "lost"
	room.hub.Register(userID, conn)
	defer func() {
		room.hub.Unregister(userID)
		// Releases the slot ONLY if this session still owns it (see
		// ClaimIdentitySlot/ReleaseIdentitySlot), a more recent
		// reconnection of the SAME identity may have already replaced it.
		room.ReleaseIdentitySlot(result.MatchedRootIdentityPub, userID)
		zeroBytes(sess.SessionKey) // zero the cryptographic material before releasing the session
		room.sessions.Remove(userID)
		// Context independent from ctx: this connection's own ctx is
		// already canceled by this point (ping failure, or the "defer
		// cancel()" above, which runs first in LIFO order), using it here
		// would make the write to every other connected user fail
		// IMMEDIATELY, regardless of their connection's health.
		// Hub.Broadcast treats any write failure as a "dead connection" and
		// removes it from the hub: without this separate context, ONE
		// user's disconnection would spuriously disconnect everyone else.
		bctx, bcancel := context.WithTimeout(context.Background(), 5*time.Second)
		room.hub.Broadcast(bctx, wsUserLeft{Type: "user_left", UserID: userID, Reason: exitReason}, "")
		bcancel()
		// If this was the last connected member, releases the room's
		// runtime state (or the entire entry, if it has no valid secret
		// left either). After room.hub.Unregister above, so ConnCount()
		// already reflects this user's exit.
		a.registry.ReleaseRoomIfEmpty(result.MatchedRoomID)
	}()

	// Send connected-user list to the newly joined client (no message history).
	users := room.sessions.GetAll()
	infos := make([]userInfo, 0, len(users))
	for _, u := range users {
		infos = append(infos, userInfo{
			UserID:      u.UserID,
			Username:    u.Username,
			SessionPub:  u.SessionPub,
			MLKEMPub:    u.MLKEMPub,
			IdentityPub: u.RootIdentityPub,
		})
	}
	if err := wsjson.Write(ctx, conn, wsInitMsg{Type: "init", Users: infos}); err != nil {
		return
	}

	// Notify existing users that a new participant has joined. Context
	// independent from ctx for the same reason as the exit broadcast
	// below: don't make delivery to OTHER users depend on this
	// connection's lifecycle.
	joinBctx, joinBcancel := context.WithTimeout(context.Background(), 5*time.Second)
	room.hub.Broadcast(joinBctx, wsUserJoined{
		Type:        "user_joined",
		UserID:      sess.UserID,
		Username:    sess.Username,
		SessionPub:  sess.SessionPub,
		MLKEMPub:    sess.MLKEMPub,
		IdentityPub: sess.RootIdentityPub,
	}, userID)
	joinBcancel()

	// Message loop.
	for {
		var incoming wsIncoming
		if err := wsjson.Read(ctx, conn, &incoming); err != nil {
			if s := websocket.CloseStatus(err); s == websocket.StatusNormalClosure || s == websocket.StatusGoingAway {
				exitReason = "left"
			} else if s == websocket.StatusPolicyViolation {
				// Hub.Kick closes with this dedicated code, /grp-ban.
				exitReason = "banned"
			} else if s == statusQueueOverloaded {
				// roomDelivery.evictOverloaded closes with this dedicated
				// code, never StatusPolicyViolation: that would mean
				// "banned" for every other member (case "banned"
				// client-side), this is just a kick for a saturated queue,
				// free reconnection, no secret revocation.
				exitReason = "overloaded"
			}
			break
		}

		dbg("ws_trace: read type=%q from=%s (%s…) to=%s… transfer=%s", incoming.Type, username, shortUID(userID), shortUID(incoming.ToUserID), incoming.TransferID)

		switch incoming.Type {
		case "sender_key":
			// Route ECIES-encrypted sender key to a specific peer.
			if incoming.ToUserID == "" || len(incoming.Payload) == 0 {
				continue
			}
			data, _ := json.Marshal(wsSenderKeyFwd{
				Type:       "sender_key",
				FromUserID: userID,
				Payload:    incoming.Payload,
				MsgID:      incoming.MsgID,
			})
			_ = room.hub.SendBytes(ctx, incoming.ToUserID, data)
			zeroBytes(incoming.Payload) // zero source bytes after routing

		case "rel_bootstrap":
			// Route the ephemeral relation-key exchange to a specific peer,
			// same treatment as sender_key above.
			if incoming.ToUserID == "" || len(incoming.Payload) == 0 {
				continue
			}
			data, _ := json.Marshal(wsRelBootstrapFwd{
				Type:       "rel_bootstrap",
				FromUserID: userID,
				Payload:    incoming.Payload,
			})
			_ = room.hub.SendBytes(ctx, incoming.ToUserID, data)
			zeroBytes(incoming.Payload)

		case "rel_promote":
			// Route the "become a real contact" exchange to a specific peer,
			// same treatment as sender_key above.
			if incoming.ToUserID == "" || len(incoming.Payload) == 0 {
				continue
			}
			data, _ := json.Marshal(wsRelPromoteFwd{
				Type:       "rel_promote",
				FromUserID: userID,
				Payload:    incoming.Payload,
			})
			_ = room.hub.SendBytes(ctx, incoming.ToUserID, data)
			zeroBytes(incoming.Payload)

		case "rel_bootstrap_ack":
			// Route back to the original sender, same treatment as
			// msg_ack, no payload to propagate (see wsRelBootstrapAckFwd).
			if incoming.ToUserID == "" {
				continue
			}
			data, _ := json.Marshal(wsRelBootstrapAckFwd{
				Type:       "rel_bootstrap_ack",
				FromUserID: userID,
			})
			_ = room.hub.SendBytes(ctx, incoming.ToUserID, data)

		case "rel_promote_ack":
			// See rel_bootstrap_ack above, same scheme for rel_promote.
			if incoming.ToUserID == "" {
				continue
			}
			data, _ := json.Marshal(wsRelPromoteAckFwd{
				Type:       "rel_promote_ack",
				FromUserID: userID,
			})
			_ = room.hub.SendBytes(ctx, incoming.ToUserID, data)

		case "ping_probe":
			if incoming.ToUserID == "" {
				continue
			}
			data, _ := json.Marshal(wsPingProbeMsg{
				Type:       "ping_probe",
				FromUserID: userID,
				Seq:        incoming.Seq,
				SentAt:     incoming.SentAt,
			})
			_ = room.hub.SendBytes(ctx, incoming.ToUserID, data)

		case "pong_probe":
			if incoming.ToUserID == "" {
				continue
			}
			data, _ := json.Marshal(wsPongProbeMsg{
				Type:       "pong_probe",
				FromUserID: userID,
				Seq:        incoming.Seq,
				SentAt:     incoming.SentAt,
			})
			_ = room.hub.SendBytes(ctx, incoming.ToUserID, data)

		case "msg_ack":
			if incoming.ToUserID == "" {
				continue
			}
			// roomDelivery bookkeeping BEFORE forwarding, whoever is
			// acknowledging (the contact, by their root identity, not the
			// original sender) removes the entry from THEIR server-side
			// pending queue. Forwarding to the original sender (below)
			// still delivers the real recipient's direct ack, never a
			// server surrogate (see
			// "self_relay_ack" for acknowledging one's own send, a
			// distinct frame).
			room.delivery.Ack(result.MatchedRootIdentityPub, incoming.MsgID)
			data, _ := json.Marshal(wsMsgAckFwd{
				Type:       "msg_ack",
				FromUserID: userID,
				MsgID:      incoming.MsgID,
			})
			_ = room.hub.SendBytes(ctx, incoming.ToUserID, data)

		case "self_relay_ack":
			// The sender acknowledges its own self-echo to itself (see
			// roomDelivery.Dispatch), removes the entry from ITS own
			// server-side pending queue, no forwarding (no other recipient
			// to inform).
			if incoming.MsgID == "" {
				continue
			}
			room.delivery.Ack(result.MatchedRootIdentityPub, incoming.MsgID)

		case "file_announce":
			// One Send per recipient, same scheme as file_offer below, the
			// cryptographic verification phase precedes any real data.
			if len(incoming.ToUserIDs) == 0 || incoming.TransferID == "" || len(incoming.Hash) == 0 || len(incoming.AnnounceEnvelopes) == 0 {
				continue
			}
			for _, uid := range incoming.ToUserIDs {
				env, ok := incoming.AnnounceEnvelopes[uid]
				if !ok {
					continue
				}
				_ = room.hub.Send(ctx, uid, wsFileAnnounceFwd{
					Type:       "file_announce",
					FromUserID: userID,
					TransferID: incoming.TransferID,
					Hash:       incoming.Hash,
					Sig:        env.Sig,
					SigMLDSA:   env.SigMLDSA,
					SigTS:      incoming.SigTS,
				})
			}

		case "file_announce_ack":
			if incoming.ToUserID == "" || incoming.TransferID == "" {
				continue
			}
			_ = room.hub.Send(ctx, incoming.ToUserID, wsFileAnnounceAckFwd{
				Type:       "file_announce_ack",
				FromUserID: userID,
				TransferID: incoming.TransferID,
			})

		case "file_offer":
			// One Send per recipient, not a Multicast: each one receives a
			// different envelope (shared.FileOfferEnvelope), never a shared
			// value, see the comment on wsFileOfferFwd above. No signature
			// here: already verified during the announce phase.
			if len(incoming.ToUserIDs) == 0 || incoming.TransferID == "" || len(incoming.Envelopes) == 0 {
				continue
			}
			for _, uid := range incoming.ToUserIDs {
				env, ok := incoming.Envelopes[uid]
				if !ok {
					continue
				}
				_ = room.hub.Send(ctx, uid, wsFileOfferFwd{
					Type:       "file_offer",
					FromUserID: userID,
					TransferID: incoming.TransferID,
					MetaBlob:   env.MetaBlob,
				})
			}

		case "file_accept":
			if incoming.ToUserID == "" || incoming.TransferID == "" {
				continue
			}
			_ = room.hub.Send(ctx, incoming.ToUserID, wsFileAcceptFwd{
				Type:       "file_accept",
				FromUserID: userID,
				TransferID: incoming.TransferID,
			})

		case "file_reject":
			if incoming.ToUserID == "" || incoming.TransferID == "" {
				continue
			}
			_ = room.hub.Send(ctx, incoming.ToUserID, wsFileRejectFwd{
				Type:       "file_reject",
				FromUserID: userID,
				TransferID: incoming.TransferID,
			})

		case "file_chunk":
			// Targeted multicast: the sender uploads the chunk once, the
			// hub forwards it to whoever accepted without ever
			// accumulating the whole file.
			if len(incoming.ToUserIDs) == 0 || incoming.TransferID == "" || len(incoming.Payload) == 0 {
				continue
			}
			data, _ := json.Marshal(wsFileChunkFwd{
				Type:       "file_chunk",
				FromUserID: userID,
				TransferID: incoming.TransferID,
				Seq:        incoming.Seq,
				Payload:    incoming.Payload,
			})
			room.hub.MulticastBytes(ctx, incoming.ToUserIDs, data)
			zeroBytes(incoming.Payload)

		case "file_chunk_ack":
			if incoming.ToUserID == "" || incoming.TransferID == "" {
				continue
			}
			_ = room.hub.Send(ctx, incoming.ToUserID, wsFileChunkAckFwd{
				Type:       "file_chunk_ack",
				FromUserID: userID,
				TransferID: incoming.TransferID,
				Seq:        incoming.Seq,
			})

		case "file_verify_result":
			if incoming.ToUserID == "" || incoming.TransferID == "" {
				continue
			}
			_ = room.hub.Send(ctx, incoming.ToUserID, wsFileVerifyResultFwd{
				Type:       "file_verify_result",
				FromUserID: userID,
				TransferID: incoming.TransferID,
				OK:         incoming.VerifyOK,
			})

		case "file_resume":
			if incoming.ToUserID == "" || incoming.TransferID == "" {
				continue
			}
			_ = room.hub.Send(ctx, incoming.ToUserID, wsFileResumeFwd{
				Type:       "file_resume",
				FromUserID: userID,
				TransferID: incoming.TransferID,
				FromByte:   incoming.FromByte,
			})

		default:
			// Broadcast room message, reliable delivery via roomDelivery:
			// gseq assigned on arrival, independent queue for each other
			// connected contact (its own retry/kick, see delivery.go),
			// never a plain fire-and-forget fan-out.
			if len(incoming.Text) == 0 {
				continue
			}
			room.sessions.Touch(userID)
			text, sig, sigTS, contentSigs, contentSigTS := incoming.Text, incoming.Sig, incoming.SigTS, incoming.ContentSigs, incoming.ContentSigTS
			deviceSig, deviceTS, pqcSig, pqcTS := incoming.DeviceSig, incoming.DeviceTS, incoming.PqcSig, incoming.PqcTS
			buildFrame := func(gseq uint64) []byte {
				data, _ := json.Marshal(wsRawChatMsg{
					Type: "message",
					Data: wsRawMsgData{
						KeyID:        incoming.KeyID,
						Text:         text,
						Idx:          incoming.Idx,
						MsgSeq:       incoming.MsgSeq,
						GSeq:         gseq,
						Timestamp:    time.Now().UTC(),
						Sig:          sig,
						SigTS:        sigTS,
						FromUserID:   userID,
						MsgID:        incoming.MsgID,
						ContentSigs:  contentSigs,
						ContentSigTS: contentSigTS,
						DeviceSig:    deviceSig,
						DeviceTS:     deviceTS,
						PqcSig:       pqcSig,
						PqcTS:        pqcTS,
					},
				})
				return data
			}
			// The recipients are all KNOWN members of the room (root
			// identityPub, RoomRegistry), not just those connected at this
			// instant, see roomDelivery.Dispatch: an offline member still
			// stays queued, delivered on reconnection. The sender is among
			// them and so receives its own self-echo (with gseq already
			// inside, wsRawMsgData.GSeq) from the same reliable
			// per-contact queue as anyone else. The acknowledgment that
			// releases client-side backpressure (Client.pending,
			// HandleServerAck) is that self-echo itself, never a separate
			// frame: the sender confirms it with "self_relay_ack" (case
			// above) as soon as it recognizes it (parseMessage/TakeSentText).
			room.delivery.Dispatch(room.hub, a.registry.MemberIdentities(result.MatchedRoomID), incoming.MsgID, result.MatchedRootIdentityPub, buildFrame)
			zeroBytes(incoming.Text)
		}
	}

	conn.Close(websocket.StatusNormalClosure, "")
}
