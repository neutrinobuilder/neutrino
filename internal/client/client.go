// retiredEph is an outEphRing entry's position in retirement order.
type retiredEph struct {
	id string
	at time.Time
}

// retireOutEph moves the current outgoing ephemeral into outEphRing and
// generates a fresh one for the next message. Caller must hold peerMu.
func (c *Client) retireOutEph() {
	id := shared.EphID(c.outEphPub.Bytes())
	c.outEphRing[id] = c.outEphPriv
	c.outEphOrder = append(c.outEphOrder, retiredEph{id: id, at: time.Now()})
	c.expireOutEph()
	c.outEphPriv, _ = ecdh.X25519().GenerateKey(rand.Reader)
	c.outEphPub = c.outEphPriv.PublicKey()
}

// expireOutEph drops every retired ephemeral older than twice the
// message TTL: any peer message still referencing one is past its own
// TTL, so its sender re-encrypts it under a new generation (see
// reencryptExpired) instead of waiting for it to be accepted. The peer
// can never keep our private ephemerals alive beyond this bound. Caller
// must hold peerMu.
func (c *Client) expireOutEph() {
	cutoff := time.Now().Add(-2 * c.messageTTL())
	n := 0
	for n < len(c.outEphOrder) && c.outEphOrder[n].at.Before(cutoff) {
		delete(c.outEphRing, c.outEphOrder[n].id)
		n++
	}
	c.outEphOrder = c.outEphOrder[n:]
}

// pruneOutEphBefore drops every retired ephemeral older than id — the
// peer, which always references the latest of ours it has seen, just
// referenced id, so none of its later messages can reference an older
// one. Caller must hold peerMu.
func (c *Client) pruneOutEphBefore(id string) {
	for i, r := range c.outEphOrder {
		if r.id != id {
			continue
		}
		for _, old := range c.outEphOrder[:i] {
			delete(c.outEphRing, old.id)
		}
		c.outEphOrder = c.outEphOrder[i:]
		return
	}
}

// ExpectedIdx returns the next expected idx for keyID and whether the
// key is already known — used by the caller (the TUI) to decide,
// BEFORE calling DecryptMsg, whether an arrived frame should be
// processed right away (idx == expected), held in a local reordering
// buffer (idx > expected), or treated as a duplicate to still confirm
// with an ack (idx < expected). known=false — key not yet received —
// is not an error: the caller still buffers, waiting for
// StorePeerSenderKey to register it.
func (c *Client) ExpectedIdx(keyID string) (idx uint64, known bool) {
	c.peerMu.RLock()
	defer c.peerMu.RUnlock()
	if _, ok := c.peerChainKeys[keyID]; !ok {
		return 0, false
	}
	return c.peerMsgIdx[keyID], true
}

// DecryptMsg advances the HMAC ratchet (with DH mix for two-member
// rooms) by EXACTLY one step and decrypts the ciphertext — never a
// fast-forward over future idx values: an out-of-sequence arrival must
// be buffered by the caller (see ExpectedIdx) and resubmitted here only
// when its turn really comes. With zero-loss delivery (reliable queue,
// see pending.go) a packet is never lost for good, so there's no need
// to guess-recover a gap by skipping ahead in the chain — the chain
// simply waits for its turn. Returns (from, plaintext) — from is empty
// on failure or when idx isn't yet at its turn.
func (c *Client) DecryptMsg(keyID, text string, idx uint64) (from, plaintext string, dp []byte, replyTo uint64) {
	c.peerMu.Lock()
	defer c.peerMu.Unlock()

	chainKey := c.peerChainKeys[keyID]
	if chainKey == nil {
		Dbg("decrypt: keyID=%s not found (sender_key not yet received)", keyID)
		return "", "[sender key unavailable]", nil, 0
	}
	expected := c.peerMsgIdx[keyID]
	Dbg("decrypt: keyID=%s idx=%d expected=%d", keyID, idx, expected)

	if idx < expected {
		Dbg("decrypt: keyID=%s idx=%d < expected=%d → duplicate message", keyID, idx, expected)
		return "", "[duplicate message]", nil, 0
	}
	if idx > expected {
		// The caller should have buffered instead of calling here —
		// defensive, never a silent chain skip.
		Dbg("decrypt: keyID=%s idx=%d > expected=%d → not yet its turn", keyID, idx, expected)
		return "", "[waiting for earlier messages]", nil, 0
	}

	// The plain step is still needed to derive msgKey (identical with or
	// without the DH mix); nextChain here is the plain fallback,
	// overwritten below if valid DH material arrives.
	msgKey, nextChain := shared.DeriveChainStep(chainKey)
	from, plaintext, dh, dhr, dp, replyTo, ok := c.unseal(msgKey, text, seqBytes(idx))
	Dbg("decrypt: keyID=%s idx=%d ok=%v dh=%v dhr=%q", keyID, idx, ok, dh != "", dhr)
	if !ok {
		// Decrypt failed: do NOT commit the chain advance (neither the
		// plain fallback nor any DH mix further below, which isn't even
		// computed here). Leaving peerChainKeys/peerMsgIdx exactly where
		// they were lets a future well-aligned message reattach —
		// committing a state regardless (right or wrong) would turn a
		// single isolated hiccup into a permanent, cascading
		// misalignment that no subsequent reconnection or re-invite
		// could correct on its own anymore.
		return "", plaintext, nil, 0
	}

	if c.ratchetDH && dh != "" {
		if dhPubBytes, err := base64.StdEncoding.DecodeString(dh); err == nil {
			if peerPub, err := ecdh.X25519().NewPublicKey(dhPubBytes); err == nil {
				if dhr != "" {
					// The sender mixed dhr into its chain: without that
					// same ephemeral the next chain key can't be
					// computed. Refused without committing anything — the
					// caller sends no ack, so the sender re-encrypts the
					// message under a new generation once its TTL
					// expires. A plain step here would diverge the chain
					// for every later message of this generation.
					c.expireOutEph()
					retired, ok := c.outEphRing[dhr]
					if !ok {
						Dbg("decrypt: keyID=%s idx=%d dhr=%s no longer retained → refused", keyID, idx, dhr)
						return "", "", nil, 0
					}
					dhShared, err := retired.ECDH(peerPub)
					if err != nil {
						Dbg("decrypt: keyID=%s idx=%d dhr=%s ECDH failed → refused", keyID, idx, dhr)
						return "", "", nil, 0
					}
					_, nextChain = shared.DeriveChainStepDH(chainKey, dhShared)
					zeroKey(dhShared)
					c.pruneOutEphBefore(dhr)
					Dbg("decrypt: keyID=%s idx=%d DH mix applied (dhr=%s resolved)", keyID, idx, dhr)
				}
				c.peerEphPub = peerPub
			}
		}
	}

	c.peerChainKeys[keyID] = nextChain
	c.peerMsgIdx[keyID] = idx + 1

	return from, plaintext, dp, replyTo
}

// unseal decrypts ciphertext with msgKey and unmarshals the sealedMsg JSON.
// aad must match what was passed to Encrypt (sequence number as seqBytes).
// msgKey is zeroed after use regardless of outcome. dh/dhr are only set for two-member
// rooms (ratchetDH) — see sealedMsg. ok is false only on genuine AEAD failure —
// the caller (DecryptMsg) uses it to decide whether to commit the chain
// advance: a text whose literal content happens to match the error
// message "[decrypt failed]" must not be mistaken for an actual failure.
func (c *Client) unseal(msgKey []byte, ciphertext string, aad []byte) (from, plaintext, dh, dhr string, dp []byte, replyTo uint64, ok bool) {
	raw, err := shared.Decrypt(msgKey, ciphertext, aad)
	zeroKey(msgKey)
	if err != nil {
		return "", "[decrypt failed]", "", "", nil, 0, false
	}
	var p sealedMsg
	if err := json.Unmarshal(raw, &p); err != nil {
		return "", "[decrypt failed]", "", "", nil, 0, false
	}
	return p.F, p.T, p.DH, p.DHR, p.DP, p.RT, true
}

