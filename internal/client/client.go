// ── peer registry ─────────────────────────────────────────────────────────────

// RegisterSessionPub caches a peer's X25519 session public key.
func (c *Client) RegisterSessionPub(userID, pubB64 string) {
	if pubB64 == "" {
		return
	}
	pubBytes, err := base64.StdEncoding.DecodeString(pubB64)
	if err != nil {
		return
	}
	pub, err := ecdh.X25519().NewPublicKey(pubBytes)
	if err != nil {
		return
	}
	c.peerMu.Lock()
	c.peerSessionPubs[userID] = pub
	c.peerMu.Unlock()
}

// RegisterMLKEMPub caches a peer's ML-KEM-768 encapsulation key (mlkem_pub,
// learned from init/user_joined — see HandshakeResult.PeerMLKEMPub).
func (c *Client) RegisterMLKEMPub(userID string, pubBytes []byte) {
	if len(pubBytes) == 0 {
		return
	}
	pub, err := mlkem.NewEncapsulationKey768(pubBytes)
	if err != nil {
		return
	}
	c.peerMu.Lock()
	c.peerMLKEMPubs[userID] = pub
	c.peerMu.Unlock()
}

// memberEntry is a room member as known from init/user_joined: its
// member key (MemberKeyOf of the root identity key) and the username
// label it was invited under, for display only.
type memberEntry struct {
	key  string
	name string
}

// MemberKeyOf is the member key of a root identity key — the only
// identifier of a room member, the same for every member of the room
// whatever username label each one sees.
func MemberKeyOf(identityPub []byte) string {
	if len(identityPub) == 0 {
		return ""
	}
	return base64.StdEncoding.EncodeToString(identityPub)
}

// RegisterUser records a room member received from the server: its
// session userID, its root identity key and its display username. A
// reconnect (frequent over I2P, rare over Tor) assigns the same member
// a brand-new session userID — recognized by the identity key, never by
// the username: two members may share a username. The previous userID
// is pruned, otherwise peerSessionPubs and members would gain one stale
// entry per reconnect for the life of the process. A member with no
// identity key is not registered.
func (c *Client) RegisterUser(userID, username string, identityPub []byte) {
	key := MemberKeyOf(identityPub)
	if userID == "" || key == "" {
		Dbg("register_user: %s (%s) without identity key, ignored", username, ShortUID(userID))
		return
	}
	c.userMapMu.Lock()
	oldUserID := c.userIDByKey[key]
	c.userIDByKey[key] = userID
	c.members[userID] = memberEntry{key: key, name: username}
	if oldUserID != "" && oldUserID != userID {
		delete(c.members, oldUserID)
	}
	c.userMapMu.Unlock()

	if oldUserID != "" && oldUserID != userID {
		c.peerMu.Lock()
		delete(c.peerSessionPubs, oldUserID)
		delete(c.peerMLKEMPubs, oldUserID)
		c.peerMu.Unlock()
		c.forgetKeyServed(oldUserID)
	}
}

// UnregisterUser removes userID from the known members (user_left) —
// without this removal members/userIDByKey would grow one stale
// entry per departed member, and the reliable delivery queue
// (pending.go) would keep waiting forever for an ack from someone no
// longer there: every pending message still waiting for their ack is
// considered confirmed by the others (dropPendingWaiter), never blocked
// indefinitely by a member who has left the room.
func (c *Client) UnregisterUser(userID string) {
	c.userMapMu.Lock()
	if m, ok := c.members[userID]; ok {
		delete(c.members, userID)
		if c.userIDByKey[m.key] == userID {
			delete(c.userIDByKey, m.key)
		}
	}
	c.userMapMu.Unlock()
	c.dropPendingWaiter(userID)
}

// LookupUserID returns the current session userID of the member with
// the given member key, or "" if not connected.
func (c *Client) LookupUserID(memberKey string) string {
	c.userMapMu.RLock()
	id := c.userIDByKey[memberKey]
	c.userMapMu.RUnlock()
	return id
}

// LookupMemberKey returns the member key behind a session userID, or ""
// if unknown.
func (c *Client) LookupMemberKey(userID string) string {
	c.userMapMu.RLock()
	key := c.members[userID].key
	c.userMapMu.RUnlock()
	return key
}

// LookupUsername returns the display username of a session userID, or
// "" if unknown — a label, never an identifier.
func (c *Client) LookupUsername(userID string) string {
	c.userMapMu.RLock()
	name := c.members[userID].name
	c.userMapMu.RUnlock()
	return name
}

// ReadMsg reads the next JSON message from the server.
func (c *Client) ReadMsg(ctx context.Context) (map[string]any, error) {
	conn := c.conn()
	if conn == nil {
		return nil, errors.New(i18n.T("client.err_not_connected"))
	}
	var v map[string]any
	if err := wsjson.Read(ctx, conn, &v); err != nil {
		return nil, err
	}
	return v, nil
}

// Ping sends a WS ping and waits for the pong — used to detect a connection that has
// gone silently stale (no read error, but no data flowing either: a known Tor failure
// mode where a degraded circuit never delivers a clean close). Must be called
// concurrently with an active ReadMsg loop: per websocket.Conn.Ping's own contract,
// the pong is picked up by the ongoing Read, not by a separate read of its own — so if
// the read loop is truly stuck, this call correctly times out instead of hanging.
func (c *Client) Ping(ctx context.Context) error {
	conn := c.conn()
	if conn == nil {
		return errors.New(i18n.T("client.err_not_connected"))
	}
	return conn.Ping(ctx)
}

func (c *Client) Username() string { return c.username }

// Close and GracefulClose are no-ops if Conn is still nil: a room tab is created (and
// closable by the user, e.g. /grp-exit) before its background Connect() call resolves —
// see cmdInvite/cmdJoin/reconnectTab, tea.Cmd closures that call Connect
// asynchronously. Closing the tab during that window must not crash the whole TUI.
func (c *Client) Close() {
	if conn := c.conn(); conn != nil {
		conn.CloseNow()
	}
}
func (c *Client) GracefulClose() {
	if conn := c.conn(); conn != nil {
		_ = conn.Close(websocket.StatusNormalClosure, "leaving")
	}
}

