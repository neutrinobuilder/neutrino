// SendSenderKeyReliable sends OUR current sender_key to toUserID over
// the reliable delivery channel (sendSenderKeyTo → registerPending/RetryDue,
// the same mechanism already used by RotateSenderKey to distribute
// after a rotation, msg_id + ack via msg_ack) — unlike SendSenderKey
// above (fire-and-forget): once this function succeeds in WRITING
// the frame, delivery stays guaranteed even through automatic
// retransmissions. The
// write itself can still fail (peerSessionPubs/peerMLKEMPubs not yet
// populated for toUserID at this moment): the caller must retry until this returns nil at
// least once (see cmdRetrySenderKeyDistribution, tui.go).
//
// A peer that already has the current generation written to it or
// deferred for it (by a rotation, or an earlier call) is a no-op
// returning nil: a second copy would carry a new msg_id, and would
// bypass a deferral meant to keep the previous generation readable on
// their side until its backlog is acknowledged.
func (c *Client) SendSenderKeyReliable(ctx context.Context, toUserID string) error {
	c.peerMu.RLock()
	pub := c.peerSessionPubs[toUserID]
	mlkemPub := c.peerMLKEMPubs[toUserID]
	c.peerMu.RUnlock()
	if pub == nil {
		return errors.New(i18n.T("client.err_session_pub", toUserID))
	}
	if mlkemPub == nil {
		return errors.New(i18n.T("client.err_mlkem_pub", toUserID))
	}
	c.sendMu.Lock()
	defer c.sendMu.Unlock()
	if c.keyServedFor(toUserID, c.senderKeyID) {
		return nil
	}
	c.sendSenderKeyTo(ctx, toUserID, pub, mlkemPub, c.senderKey)
	return nil
}

